#!/usr/bin/env python3
"""將 models/*.glb 與 models/*.jpg 打包為 models/models.js (base64 Data URI)，
支援 file:// 雙擊開啟與線上網址零延遲載入，並滿足 quality_check.py 檢查。
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS_DIR = ROOT / "models"
OUT_JS = MODELS_DIR / "models.js"


def main():
    entries = {}
    for p in sorted(MODELS_DIR.glob("*.glb")):
        b64 = base64.b64encode(p.read_bytes()).decode("ascii")
        entries[p.stem] = f"data:model/gltf-binary;base64,{b64}"
        print(f"Packed GLB: {p.name} ({p.stat().st_size / 1024:.1f} KB)")

    for p in sorted(MODELS_DIR.glob("*.jpg")):
        b64 = base64.b64encode(p.read_bytes()).decode("ascii")
        entries[p.stem] = f"data:image/jpeg;base64,{b64}"
        print(f"Packed JPG: {p.name} ({p.stat().st_size / 1024:.1f} KB)")

    content = "// Auto-generated by tools/pack_models.py\nwindow.BIRD_MODELS = " + json.dumps(entries) + ";\n"
    OUT_JS.write_text(content, encoding="utf-8")
    print(f"Generated {OUT_JS} ({OUT_JS.stat().st_size / 1024:.1f} KB)")


if __name__ == "__main__":
    main()
